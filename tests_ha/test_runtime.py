"""Home Assistant runtime acceptance tests with virtual (nonphysical) actors."""
import asyncio

import pytest
from homeassistant.config_entries import ConfigEntryState
from homeassistant.core import HomeAssistant
from homeassistant.setup import async_setup_component
from pytest_homeassistant.common import MockConfigEntry


@pytest.mark.asyncio
async def test_two_circuits_load_entities_and_unload_without_switching(hass: HomeAssistant):
    assert await async_setup_component(hass, "http", {})
    assert await async_setup_component(hass, "websocket_api", {})

    first = MockConfigEntry(
        domain="wetsoil", title="Test 1",
        unique_id="wetsoil-test-1",
        data={"name": "Test 1", "area_id": None},
    )
    second = MockConfigEntry(
        domain="wetsoil", title="Test 2",
        unique_id="wetsoil-test-2",
        data={"name": "Test 2", "area_id": None},
    )
    first.add_to_hass(hass)
    second.add_to_hass(hass)
    # Home Assistant may eagerly set up the second entry while setting up
    # the domain for the first. Do not redundantly setup an already loaded one.
    await hass.config_entries.async_setup(first.entry_id)
    await hass.async_block_till_done()
    if second.state is ConfigEntryState.NOT_LOADED:
        await hass.config_entries.async_setup(second.entry_id)
        await hass.async_block_till_done()

    assert first.state is ConfigEntryState.LOADED
    assert second.state is ConfigEntryState.LOADED
    assert first.entry_id in hass.data["wetsoil"]
    assert second.entry_id in hass.data["wetsoil"]
    from homeassistant.helpers import entity_registry as er
    registry = er.async_get(hass)
    ids = {
        item.config_entry_id: set()
        for item in er.async_entries_for_config_entry(registry, first.entry_id)
        + er.async_entries_for_config_entry(registry, second.entry_id)
    }
    assert first.entry_id in ids and second.entry_id in ids
    assert await hass.config_entries.async_unload(first.entry_id)
    assert second.entry_id in hass.data["wetsoil"]


@pytest.mark.asyncio
async def test_config_flow_only_requests_name_and_area(hass: HomeAssistant):
    from custom_components.wetsoil.config_flow import WetSoilConfigFlow
    from homeassistant.helpers import selector
    # Inspect the real form generated by the actual Config Flow step.
    flow = WetSoilConfigFlow()
    result = await flow.async_step_user()
    assert result["type"].value == "form"
    schema=result["data_schema"].schema
    names={str(key) for key in schema}
    assert "name" in names and "area_id" in names
    assert len(schema)==2
